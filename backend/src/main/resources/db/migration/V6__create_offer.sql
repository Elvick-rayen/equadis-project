CREATE TABLE offer (
    id                     BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    -- No ON DELETE CASCADE: a supplier with offers cannot be deleted.
    supplier_id            BIGINT        NOT NULL REFERENCES supplier (id),
    reference              VARCHAR(40)   NOT NULL,
    title                  VARCHAR(120)  NOT NULL,
    description            VARCHAR(2000),
    discount_type          VARCHAR(30)   NOT NULL,
    discount_value         NUMERIC(12,2) NOT NULL,
    currency               VARCHAR(3),
    minimum_order_quantity INTEGER,
    valid_from             DATE          NOT NULL,
    valid_to               DATE          NOT NULL,
    status                 VARCHAR(10)   NOT NULL,
    version                BIGINT        NOT NULL DEFAULT 0,
    CONSTRAINT ck_offer_status CHECK (status IN ('DRAFT', 'PUBLISHED', 'CLOSED')),
    -- BR-09
    CONSTRAINT ck_offer_validity CHECK (valid_to >= valid_from),
    CONSTRAINT ck_offer_discount CHECK (
        (discount_type = 'PERCENTAGE_DISCOUNT' AND discount_value > 0 AND discount_value <= 100 AND currency IS NULL)
     OR (discount_type = 'FIXED_AMOUNT_DISCOUNT' AND discount_value > 0 AND currency ~ '^[A-Z]{3}$')
    ),
    CONSTRAINT ck_offer_min_quantity CHECK (minimum_order_quantity IS NULL OR minimum_order_quantity > 0)
);

-- A reference is unique per supplier, ignoring case.
CREATE UNIQUE INDEX uk_offer_reference ON offer (supplier_id, lower(reference));
-- "Offers available today" (BR-10).
CREATE INDEX ix_offer_available ON offer (status, valid_from, valid_to);
