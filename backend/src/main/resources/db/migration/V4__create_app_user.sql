-- Login accounts. A supplier or retailer account belongs to exactly one company;
-- deleting the company deletes its account.
CREATE TABLE app_user (
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    username      VARCHAR(50)  NOT NULL,
    password_hash VARCHAR(100) NOT NULL,
    role          VARCHAR(20)  NOT NULL REFERENCES persona (code),
    supplier_id   BIGINT REFERENCES supplier (id) ON DELETE CASCADE,
    retailer_id   BIGINT REFERENCES retailer (id) ON DELETE CASCADE,
    version       BIGINT       NOT NULL DEFAULT 0,
    CONSTRAINT ck_app_user_company CHECK (
        (role = 'ADMIN'    AND supplier_id IS NULL     AND retailer_id IS NULL)
     OR (role = 'SUPPLIER' AND supplier_id IS NOT NULL AND retailer_id IS NULL)
     OR (role = 'RETAILER' AND retailer_id IS NOT NULL AND supplier_id IS NULL)
    )
);

CREATE UNIQUE INDEX uk_app_user_username ON app_user (lower(username));
