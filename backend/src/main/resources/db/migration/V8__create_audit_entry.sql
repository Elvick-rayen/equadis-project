-- Append-only log of partnership and offer actions (bonus: audit log).
CREATE TABLE audit_entry (
    id           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    occurred_at  TIMESTAMPTZ  NOT NULL,
    actor        VARCHAR(120) NOT NULL,
    action       VARCHAR(40)  NOT NULL,
    subject_type VARCHAR(20)  NOT NULL,
    subject_id   BIGINT       NOT NULL,
    details      VARCHAR(600),
    CONSTRAINT ck_audit_subject_type CHECK (subject_type IN ('PARTNERSHIP', 'OFFER'))
);

CREATE INDEX ix_audit_entry_occurred ON audit_entry (occurred_at DESC);
CREATE INDEX ix_audit_entry_subject ON audit_entry (subject_type, subject_id);
