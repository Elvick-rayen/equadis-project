CREATE TABLE retailer (
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    store_name    VARCHAR(120) NOT NULL,
    store_type    VARCHAR(10)  NOT NULL,
    country_code  VARCHAR(2)   NOT NULL,
    city          VARCHAR(120),
    address       VARCHAR(200),
    website       VARCHAR(255),
    contact_email VARCHAR(254) NOT NULL,
    version       BIGINT       NOT NULL DEFAULT 0,
    CONSTRAINT ck_retailer_store_type CHECK (store_type IN ('ONLINE', 'PHYSICAL', 'HYBRID')),
    CONSTRAINT ck_retailer_country_code CHECK (country_code ~ '^[A-Z]{2}$'),
    -- BR-02: ONLINE needs a website, PHYSICAL needs address and city, HYBRID needs all three.
    CONSTRAINT ck_retailer_location CHECK (
        (store_type <> 'PHYSICAL' OR (city IS NOT NULL AND address IS NOT NULL))
        AND (store_type <> 'ONLINE' OR website IS NOT NULL)
        AND (store_type <> 'HYBRID' OR (city IS NOT NULL AND address IS NOT NULL AND website IS NOT NULL))
    )
);
