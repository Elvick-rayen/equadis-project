CREATE TABLE subscription (
    id                 BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    -- No ON DELETE CASCADE: a retailer with subscriptions cannot be deleted.
    retailer_id        BIGINT      NOT NULL REFERENCES retailer (id),
    offer_id           BIGINT      NOT NULL REFERENCES offer (id),
    -- The offer's supplier, copied so a terminated partnership finds its subscriptions directly.
    supplier_id        BIGINT      NOT NULL REFERENCES supplier (id),
    subscribed_on      DATE        NOT NULL,
    cancelled_on       DATE,
    cancellation_cause VARCHAR(30),
    version            BIGINT      NOT NULL DEFAULT 0,
    CONSTRAINT ck_subscription_cancellation CHECK ((cancelled_on IS NULL) = (cancellation_cause IS NULL)),
    CONSTRAINT ck_subscription_cause CHECK (
        cancellation_cause IS NULL OR cancellation_cause IN ('RETAILER_REQUEST', 'OFFER_CLOSED', 'PARTNERSHIP_TERMINATED')
    )
);

-- BR-11: at most one active (not cancelled) subscription per retailer and offer.
CREATE UNIQUE INDEX uk_subscription_active ON subscription (retailer_id, offer_id) WHERE cancelled_on IS NULL;
CREATE INDEX ix_subscription_offer ON subscription (offer_id) WHERE cancelled_on IS NULL;
CREATE INDEX ix_subscription_retailer_supplier ON subscription (retailer_id, supplier_id);
