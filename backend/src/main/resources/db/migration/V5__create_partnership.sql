-- btree_gist lets an exclusion constraint combine "=" on ids with "&&" on date ranges.
CREATE EXTENSION IF NOT EXISTS btree_gist;

-- Status (SCHEDULED, ACTIVE, EXPIRED, TERMINATED) is not stored: it is computed from today's
-- date and terminated_on every time it is read (BR-05).
CREATE TABLE partnership (
    id                 BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    -- No ON DELETE CASCADE: a supplier or retailer with partnerships cannot be deleted.
    supplier_id        BIGINT       NOT NULL REFERENCES supplier (id),
    retailer_id        BIGINT       NOT NULL REFERENCES retailer (id),
    start_date         DATE         NOT NULL,
    end_date           DATE         NOT NULL,
    terminated_on      DATE,
    termination_reason VARCHAR(500),
    version            BIGINT       NOT NULL DEFAULT 0,
    -- BR-03 (end after start); the other BR-03 checks depend on "today" and live in the domain.
    CONSTRAINT ck_partnership_period CHECK (end_date > start_date),
    -- BR-07: a terminated partnership always has its reason.
    CONSTRAINT ck_partnership_termination CHECK ((terminated_on IS NULL) = (termination_reason IS NULL)),
    -- BR-04: no two non-terminated partnerships of the same pair may overlap (both ends included).
    CONSTRAINT ex_partnership_overlap EXCLUDE USING gist (
        supplier_id WITH =,
        retailer_id WITH =,
        daterange(start_date, end_date, '[]') WITH &&
    ) WHERE (terminated_on IS NULL)
);

CREATE INDEX ix_partnership_retailer ON partnership (retailer_id);
CREATE INDEX ix_partnership_end_date ON partnership (end_date);

-- BR-06: every renewal is kept.
CREATE TABLE partnership_renewal (
    id                BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    partnership_id    BIGINT NOT NULL REFERENCES partnership (id) ON DELETE CASCADE,
    previous_end_date DATE   NOT NULL,
    new_end_date      DATE   NOT NULL,
    renewed_on        DATE   NOT NULL,
    CONSTRAINT ck_renewal_extends CHECK (new_end_date > previous_end_date)
);

CREATE INDEX ix_partnership_renewal_partnership ON partnership_renewal (partnership_id);
